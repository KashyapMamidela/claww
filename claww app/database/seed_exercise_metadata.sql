  harder_variation_id = (SELECT h.id FROM exercises h WHERE h.name = v.harder),
  easier_variation_id = (SELECT x.id FROM exercises x WHERE x.name = v.easier)
FROM (VALUES
  ('Bench Dip', 'Bodyweight Dip', NULL),
  ('Bird Dog', 'Plank', NULL),
  ('Bodyweight Dip', NULL, 'Decline Push-Up'),
  ('Bodyweight Lunge', 'Bulgarian Split Squat', NULL),
  ('Bodyweight Squat', 'Bulgarian Split Squat', NULL),
  ('Bulgarian Split Squat', 'Pistol Squat', 'Bodyweight Squat'),
  ('Chin-Up', 'Pull-Up', 'Inverted Row'),
  ('Decline Push-Up', 'Bodyweight Dip', 'Push-Up'),
  ('Glute Bridge', 'Single-Leg Glute Bridge', NULL),
  ('Hollow Body Hold', 'V-Up', 'Plank'),
  ('Incline Push-Up', 'Push-Up', NULL),
  ('Inverted Row', 'Chin-Up', NULL),
  ('Pistol Squat', NULL, 'Bulgarian Split Squat'),
  ('Plank', 'Hollow Body Hold', 'Bird Dog'),
  ('Pull-Up', NULL, 'Chin-Up'),
  ('Push-Up', 'Decline Push-Up', 'Incline Push-Up'),
  ('Reverse Lunge', 'Bulgarian Split Squat', NULL),
  ('Single-Leg Glute Bridge', NULL, 'Glute Bridge'),
  ('Step-Up', 'Bulgarian Split Squat', NULL),
  ('V-Up', NULL, 'Hollow Body Hold'),
  ('Wall Sit', 'Bulgarian Split Squat', NULL)
) AS v(name, harder, easier)
WHERE e.name = v.name;
