--   never loadable and are not progressed by the adaptive engine.
--   loadable = FALSE for bodyweight and resistance-band moves.
--   load_increment_kg: 2.5 barbell and machine, 2.0 dumbbell
--   compound, 1.0 dumbbell isolation, 4.0 kettlebell.
--   stimulus_type: compound | isolation | isometric | plyometric
